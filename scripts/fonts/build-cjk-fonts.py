"""Build bundled web fonts from the pinned releases in sources.json.

Requires fonttools[woff]==4.68.0. Download each source TTF and license named in
sources.json into one directory, then run with --source-dir <directory>.
Only web-delivery subsets are produced; original outlines/names are retained.
"""
import argparse
from collections import defaultdict
from concurrent.futures import ProcessPoolExecutor
import hashlib
import io
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parents[2]
CONFIG = Path(__file__).with_name('sources.json')


def build_chunk(job):
    source, output, stem, points, selectors, web_family = job
    font = TTFont(source, recalcTimestamp=False)
    if web_family:
        rename_web_font(font, web_family)
    options = subset.Options()
    options.flavor = 'woff2'
    options.layout_features = ['*']
    options.name_IDs = ['*']
    options.name_languages = ['*']
    options.name_legacy = True
    worker = subset.Subsetter(options=options)
    worker.populate(unicodes=points + selectors)
    worker.subset(font)
    font.flavor = 'woff2'
    buffer = io.BytesIO()
    font.save(buffer)
    content = buffer.getvalue()
    checksum = hashlib.sha256(content).hexdigest()
    name = f'{stem}-{checksum[:16]}.woff2'
    (Path(output) / name).write_bytes(content)
    # Ranges describe the original cmap, never an approximate CJK block.
    ranges = []
    for point in points:
        if ranges and point == ranges[-1][1] + 1:
            ranges[-1][1] = point
        else:
            ranges.append([point, point])
    unicode_range = ','.join(f'U+{a:X}' + (f'-{b:X}' if a != b else '') for a, b in ranges)
    return dict(file=name, sha256=checksum, bytes=len(content), unicodeRange=unicode_range)


def rename_web_font(font, family):
    """IPA web derivatives use a distinct internal/file name; keep copyrights."""
    names = {
        1: family, 3: family + ' Web', 4: family + ' Regular',
        6: family.replace(' ', '') + '-Regular', 16: family, 18: family + ' Regular',
        21: family, 25: family.replace(' ', ''),
    }
    for record in font['name'].names:
        if record.nameID in names:
            record.string = names[record.nameID].encode(record.getEncoding())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir', required=True, type=Path)
    parser.add_argument('--workers', type=int, default=2)
    args = parser.parse_args()
    config = json.loads(CONFIG.read_text(encoding='utf-8'))
    for item in config:
        source = args.source_dir / item['sourceFile']
        assert hashlib.sha256(source.read_bytes()).hexdigest() == item['sourceSha256'], 'Source checksum mismatch'
        output = ROOT / 'packages/excalidraw/fonts' / item['directory']
        output.mkdir(exist_ok=True)
        # Refuse to mix generated chunks with prior, potentially user-owned files.
        assert not list(output.glob('*.woff2')), f'{output} already contains web fonts'
        license_text = (args.source_dir / item['licenseFile']).read_text(encoding='utf-8')
        (output / item['licenseFile']).write_bytes((args.source_dir / item['licenseFile']).read_bytes())
        (output / 'license.ts').write_text('export const license = ' + json.dumps(license_text, ensure_ascii=False) + ';\n', encoding='utf-8')
        font = TTFont(source)
        points = sorted(font.getBestCmap())
        groups = defaultdict(list)
        for point in points:
            groups[point // 512].append(point)
        selectors = sorted({selector for table in font['cmap'].tables if table.format == 14 for selector in table.uvsDict})
        jobs = [(str(source), str(output), item['directory'] + '-Regular', group, selectors, item.get('webFamily')) for group in groups.values()]
        with ProcessPoolExecutor(max_workers=args.workers) as pool:
            chunks = list(pool.map(build_chunk, jobs))
        imports = '\n'.join(f'import chunk{i} from "./{chunk["file"]}";' for i, chunk in enumerate(chunks))
        faces = ',\n'.join('  { uri: chunk' + str(i) + ', license, descriptors: { unicodeRange: ' + json.dumps(chunk['unicodeRange']) + ' } }' for i, chunk in enumerate(chunks))
        (output / 'index.ts').write_text('// Generated by scripts/fonts/build-cjk-fonts.py; see README.md.\nimport { license } from "./license";\n' + imports + '\n\nimport type { ExcalidrawFontFaceDescriptor } from "../Fonts";\n\nexport const ' + item['export'] + ': ExcalidrawFontFaceDescriptor[] = [\n' + faces + '\n];\n', encoding='utf-8')
        metrics = dict(unitsPerEm=font['head'].unitsPerEm, ascender=font['hhea'].ascent, descender=font['hhea'].descent, lineHeight=1.25)
        manifest = dict(**item, metrics=metrics, codepointCount=len(points), chunks=chunks)
        (output / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
        readme = f'# {item["displayName"]}\n\nPinned source: [{item["repository"]} {item["version"]}]({item["sourceURL"]}).\n\n- Source SHA-256: `{item["sourceSha256"]}`.\n- License: [{item["licenseFile"]}](./{item["licenseFile"]}); the original names and license metadata are retained.\n- Glyph outlines are unchanged; only Unicode web-delivery subsets and WOFF2 conversion are applied.\n- `{len(points)}` codepoints, `{len(chunks)}` chunks, `{sum(c["bytes"] for c in chunks)}` bytes.\n- Regenerate with `scripts/fonts/build-cjk-fonts.py`; `manifest.json` records every checksum and Unicode range.\n- The application adds `Calileon ` only to the picker label. CSS and stored font identifiers keep their stable names.\n\nOriginal font: [{item["sourceFile"]}]({item["sourceURL"]}). To use the unmodified upstream version on a desktop, install that file instead of these web-only subsets.\n'
        if item.get('webFamily'):
            readme = readme.replace('the original names and license metadata are retained', 'copyrights and license metadata are retained; the web derivative uses the distinct internal name `' + item['webFamily'] + '`')
            readme = readme.replace('only Unicode web-delivery subsets and WOFF2 conversion are applied', 'Unicode web-delivery subsets, WOFF2 conversion and distinct internal/file naming are applied')
            readme += '\n## Replacing the web derivative with the original\n\nDownload the upstream original linked above. Register that original TTF as a FontFace under the CSS alias `' + item['webFamily'] + '` instead of these subsets. For the first released IPA font, see [IPA fonts](https://moji.or.jp/ipafont/).\n'
        (output / 'README.md').write_text(readme, encoding='utf-8')
        print(json.dumps(dict(font=item['family'], metrics=metrics, chunks=len(chunks), bytes=sum(c['bytes'] for c in chunks))), flush=True)


if __name__ == '__main__':
    main()
